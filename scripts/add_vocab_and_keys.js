const langs = ['en', 'ta', 'hi', 'te', 'ml', 'kn', 'bn', 'mr'];

for (const lang of langs) {
  const filePath = path.join(trDir, `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // We need to parse the exported object or insert the new namespaces
  // Notice each file has: export const <lang> = { ... };
  // Let's find the closing "};" of the exported object.
  // In en.ts, it has "export type TranslationSchema = typeof en;" after "};"
  
  const toInsert = `  "vocab": ${JSON.stringify(vocabData[lang].vocab, null, 4).replace(/^/gm, '  ').trim()},\n  "tableHeaders": ${JSON.stringify(vocabData[lang].tableHeaders, null, 4).replace(/^/gm, '  ').trim()},\n  "dashboardLabels": ${JSON.stringify(vocabData[lang].dashboardLabels, null, 4).replace(/^/gm, '  ').trim()},\n`;

  // Find the last occurrence of "};"
  // If it has export type, it's before that.
  let insertIdx = -1;
  if (content.includes('export type TranslationSchema')) {
    insertIdx = content.indexOf('export type TranslationSchema');
    // find the "};" right before that
    insertIdx = content.lastIndexOf('};', insertIdx);
  } else {
    insertIdx = content.lastIndexOf('};');
  }

  if (insertIdx !== -1) {
    const newContent = content.slice(0, insertIdx) + toInsert + content.slice(insertIdx);
    fs.writeFileSync(filePath, newContent, 'utf8');
    console.log(`Updated ${lang}.ts with vocab, tableHeaders, and dashboardLabels`);
  } else {
    console.error(`Could not find closing brace in ${lang}.ts`);
  }
}
